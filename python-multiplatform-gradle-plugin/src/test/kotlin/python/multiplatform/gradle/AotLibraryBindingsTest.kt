/**
 * The Kotlin generator for a TypedPython AOT library (SPEC N-17, #458): `<prefix>.json` in, Kotlin text out.
 *
 * The description below is written by hand in the format of `typedpython/aot/library.py` (abi_version 1) and holds
 * every type of the boundary vocabulary: scalars, both lists, a tuple return, a None return, and parameter and
 * function names that are Kotlin hard keywords. The expected text is asserted on signatures, on the carrier
 * descriptor of each symbol, on the status check and exception path, and on the rules the desktop FFM code of this
 * repository follows (invokeExact, pointers as long). Provenance: owner decision D5 (2026-11-16) for the library
 * output; the generated shape is an agent proposal, not owner-confirmed.
 */
class AotLibraryBindingsTest {

    private fun description(abi: Int = 1, extraFunction: String = ""): String = """
        {
          "prefix": "kit",
          "library": "libkit.dylib",
          "abi_version": $abi,
          "runtime": {"init": "kit_init", "shutdown": "kit_shutdown", "last_error": "kit_last_error"},
          "functions": [
            {"name": "add", "symbol": "kit_add", "line": 1,
             "params": [{"name": "a", "type": "i64"}, {"name": "b", "type": "i64"}], "returns": ["i64"]},
            {"name": "scale", "symbol": "kit_scale", "line": 2,
             "params": [{"name": "x", "type": "f64"}, {"name": "flag", "type": "bool"}], "returns": ["f64"]},
            {"name": "is_big", "symbol": "kit_is_big", "line": 3,
             "params": [{"name": "x", "type": "f64"}], "returns": ["bool"]},
            {"name": "fill", "symbol": "kit_fill", "line": 4,
             "params": [{"name": "v", "type": "f64_list"}, {"name": "w", "type": "i64_list"}], "returns": []},
            {"name": "make_values", "symbol": "kit_make_values", "line": 5,
             "params": [{"name": "n", "type": "i64"}], "returns": ["f64_list"]},
            {"name": "make_ints", "symbol": "kit_make_ints", "line": 6,
             "params": [], "returns": ["i64_list"]},
            {"name": "split_pair", "symbol": "kit_split_pair", "line": 7,
             "params": [{"name": "a", "type": "i64"}], "returns": ["i64", "f64", "bool"]},
            {"name": "two", "symbol": "kit_two", "line": 8,
             "params": [], "returns": ["i64", "i64"]},
            {"name": "keywords", "symbol": "kit_keywords", "line": 9,
             "params": [{"name": "in", "type": "i64"}, {"name": "object", "type": "f64"}], "returns": ["f64"]},
            {"name": "when", "symbol": "kit_when", "line": 10,
             "params": [], "returns": []}$extraFunction
          ],
          "lists": {
            "f64_list": {"element": "f64", "new": "kit_f64_list_new", "len": "kit_f64_list_len",
                         "data": "kit_f64_list_data", "retain": "kit_f64_list_retain", "release": "kit_f64_list_release"},
            "i64_list": {"element": "i64", "new": "kit_i64_list_new", "len": "kit_i64_list_len",
                         "data": "kit_i64_list_data", "retain": "kit_i64_list_retain", "release": "kit_i64_list_release"}
          }
        }
    """.trimIndent()

    private fun render(pkg: String = "fixture.kit", name: String = "Kit", json: String = description()) =
        renderAotLibraryBindings(parseAotLibraryDescription(json), pkg, name)

    private val objectText get() = render().getValue("Kit.kt")

    @Test
    fun itWritesTheHelperTheObjectAndBothListClasses() {
        assertEquals(listOf("AotFfm.kt", "Kit.kt", "F64List.kt", "I64List.kt"), render().keys.toList())
        for ((file, text) in render()) {
            assertTrue(text.startsWith("// GENERATED by python-multiplatform-gradle-plugin"), "$file has no generated notice")
            assertTrue(text.contains("\npackage fixture.kit\n"), "$file is not in the given package")
        }
    }

    @Test
    fun everyFunctionHasKotlinTypesAndKeepsItsPythonNames() {
        val kit = objectText
        assertTrue(kit.contains("    fun add(a: Long, b: Long): Long {"), kit)
        assertTrue(kit.contains("    fun scale(x: Double, flag: Boolean): Double {"), kit)
        assertTrue(kit.contains("    fun is_big(x: Double): Boolean {"), "snake_case is kept")
        assertTrue(kit.contains("    fun fill(v: F64List, w: I64List) {"), "None is Unit, the function has no result type")
        assertTrue(kit.contains("    fun make_values(n: Long): F64List {"), kit)
        assertTrue(kit.contains("    fun make_ints(): I64List {"), kit)
        assertTrue(kit.contains("    fun split_pair(a: Long): SplitPairResult {"), kit)
        assertTrue(kit.contains("    fun two(): TwoResult {"), "a tuple of two is a data class too, not a Pair")
    }

    @Test
    fun aTupleReturnIsAGeneratedDataClassInOrder() {
        val kit = objectText
        assertTrue(kit.contains("data class SplitPairResult(val v0: Long, val v1: Double, val v2: Boolean)"), kit)
        assertTrue(kit.contains("data class TwoResult(val v0: Long, val v1: Long)"), kit)
        assertTrue(
            kit.contains(
                "return SplitPairResult(__h.rt.readLong(__out), __h.rt.readDouble(__out + 8L), " +
                    "__h.rt.readByte(__out + 16L).toInt() != 0)",
            ),
            kit,
        )
    }

    @Test
    fun aKotlinHardKeywordIsBackticked() {
        val kit = objectText
        assertTrue(kit.contains("    fun keywords(`in`: Long, `object`: Double): Double {"), kit)
        assertTrue(kit.contains("kit_keywords"), kit)
        assertTrue(kit.contains("    fun `when`() {"), "a function named like a keyword")
        assertTrue(kit.contains("f_keywords.invokeExact(`in`, `object`, __out) as Int"), kit)
        assertEquals("`in`", aotKotlinName("in"))
        assertEquals("`val`", aotKotlinName("val"))
        assertEquals("steps", aotKotlinName("steps"))
    }

    @Test
    fun theDescriptorOfEachSymbolIsMadeOfCarrierTypesOnly() {
        val kit = objectText
        // J long (every pointer and int64_t), D double, B byte (uint8_t), I int status; out pointers are J.
        for ((symbol, descriptor) in mapOf(
            "kit_add" to "(JJJ)I",
            "kit_scale" to "(DBJ)I",
            "kit_is_big" to "(DJ)I",
            "kit_fill" to "(JJ)I",
            "kit_make_values" to "(JJ)I",
            "kit_make_ints" to "(J)I",
            "kit_split_pair" to "(JJJJ)I",
            "kit_two" to "(JJ)I",
            "kit_keywords" to "(JDJ)I",
            "kit_when" to "()I",
            "kit_init" to "()I",
            "kit_last_error" to "(JJ)I",
            "kit_f64_list_new" to "(J)J",
            "kit_f64_list_len" to "(J)J",
            "kit_f64_list_data" to "(J)J",
            "kit_f64_list_retain" to "(J)V",
            "kit_i64_list_release" to "(J)V",
        )) {
            assertTrue(kit.contains("rt.downcall(\"$symbol\", \"$descriptor\")"), "$symbol should be bound as $descriptor:\n$kit")
        }
    }

    @Test
    fun noDescriptorUsesAnAddressOrAnObjectCarrier() {
        val all = render().values.joinToString("\n")
        assertFalse(Regex("rt\\.downcall\\(\"[^\"]+\", \"[^\"]*[^JDBIV()][^\"]*\"\\)").containsMatchIn(all))
        assertFalse(all.contains("ADDRESS"), "pointers are JAVA_LONG, never ADDRESS")
        assertTrue(render().getValue("AotFfm.kt").contains("getField(\"JAVA_LONG\")"))
    }

    @Test
    fun aCallIsOneInvokeExactAndAFailureThrowsTheLibrariesException() {
        val kit = objectText
        assertTrue(kit.contains("val __rc = __h.f_add.invokeExact(a, b, __out) as Int"), kit)
        assertTrue(kit.contains("if (__rc != 0) throw __h.rt.lastError(__h.lastError)"), kit)
        // the per-call code never reflects and never uses the inexact invoke
        assertFalse(kit.contains(".invoke("), "generated functions must not use MethodHandle.invoke")
        assertFalse(kit.contains("getMethod"), kit)
        // bool arguments are bytes, lists are their handles, the status is read before the out value
        assertTrue(kit.contains("f_scale.invokeExact(x, (if (flag) 1 else 0).toByte(), __out) as Int"), kit)
        assertTrue(kit.contains("f_fill.invokeExact(v.pointer(), w.pointer()) as Int"), kit)
        assertTrue(
            kit.indexOf("if (__rc != 0) throw", kit.indexOf("fun add(")) < kit.indexOf("return __h.rt.readLong(__out)", kit.indexOf("fun add(")),
        )
        // a returned list becomes an owned handle
        assertTrue(kit.contains("return F64List.owned(__h, __h.rt.readLong(__out))"), kit)
        assertTrue(kit.contains("return I64List.owned(__h, __h.rt.readLong(__out))"), kit)
        // a function with no result has no out pointer
        assertFalse(kit.substringAfter("fun fill(").substringBefore("}").contains("__out"))
    }

    @Test
    fun theObjectLoadsOnceAndTheHelperReadsTheErrorRecord() {
        val kit = objectText
        assertTrue(kit.contains("object Kit {"), kit)
        assertTrue(kit.contains("    @Synchronized\n    fun load(libraryPath: String) {"), kit)
        assertTrue(kit.contains("handles.aotInit.invokeExact() as Int"), kit)
        val helper = render().getValue("AotFfm.kt")
        assertTrue(helper.contains("class TypedPythonAotException(val className: String, message: String) : RuntimeException(message)"))
        assertTrue(helper.contains("fun lastError(lastErrorHandle: MethodHandle): TypedPythonAotException"))
        assertTrue(helper.contains("ThreadLocal.withInitial"), "out pointers live in per-thread scratch memory")
    }

    @Test
    fun theListClassesAreClosableBoundsCheckedAndNameTheLibraryObject() {
        val f64 = render().getValue("F64List.kt")
        assertTrue(f64.contains("class F64List private constructor(private val lib: Kit.Handles, pointer: Long) : AutoCloseable {"), f64)
        assertTrue(f64.contains("operator fun get(index: Int): Double {"), f64)
        assertTrue(f64.contains("operator fun set(index: Int, value: Double) {"), f64)
        assertTrue(f64.contains("fun toDoubleArray(): DoubleArray {"), f64)
        assertTrue(f64.contains("fun of(values: DoubleArray): F64List {"), f64)
        assertTrue(f64.contains("throw IndexOutOfBoundsException("), f64)
        assertTrue(f64.contains("throw IllegalStateException(\"F64List is closed\")"), f64)
        assertTrue(f64.contains("owner.getAndSet(0L)"), "close releases once")
        assertTrue(f64.contains("lib.f64ListRelease.invokeExact(p) as Unit"), f64)
        assertTrue(f64.contains("caller's responsibility"), "the concurrency rule is documented on the class")
        val i64 = render().getValue("I64List.kt")
        assertTrue(i64.contains("operator fun get(index: Int): Long {"), i64)
        assertTrue(i64.contains("fun toLongArray(): LongArray {"), i64)
        assertTrue(i64.contains("lib.i64ListRelease.invokeExact(p) as Unit"), i64)
    }

    @Test
    fun theHelperIsTheSameTextForEveryLibraryButItsPackage() {
        val a = renderAotLibraryBindings(parseAotLibraryDescription(description()), "one.pkg", "One").getValue("AotFfm.kt")
        val b = renderAotLibraryBindings(parseAotLibraryDescription(description()), "two.other", "Two").getValue("AotFfm.kt")
        assertEquals(a.replace("package one.pkg", "package X"), b.replace("package two.other", "package X"))
        assertFalse(a.contains("%PACKAGE%"))
    }

    @Test
    fun theGeneratedSourcesUseOnlyTheStandardLibraryAndJavaBase() {
        val imports = render().values.flatMap { it.lines() }.filter { it.startsWith("import ") }.toSet()
        for (i in imports) {
            assertTrue(i.startsWith("import java.") || i.startsWith("import kotlin."), "only java.base and kotlin: $i")
        }
        assertFalse(render().values.any { it.contains("python.multiplatform") || it.contains("python.native") })
    }

    // --- task failures --------------------------------------------------------------------------------

    @Test
    fun aWrongAbiVersionIsAClearFailure() {
        val e = assertFailsWith<GradleException> { parseAotLibraryDescription(description(abi = 2)) }
        assertTrue(e.message!!.contains("abi_version 2"), e.message)
        assertTrue(e.message!!.contains("abi_version 1"), e.message)
        assertFailsWith<GradleException> { parseAotLibraryDescription(description().replace("\"abi_version\": 1,", "")) }
    }

    @Test
    fun anUnknownTypeFailsNamingTheFunction() {
        val badReturn = description(extraFunction = ",\n" + """{"name": "label", "symbol": "kit_label", "line": 11, "params": [], "returns": ["str"]}""")
        val e = assertFailsWith<GradleException> { parseAotLibraryDescription(badReturn) }
        assertTrue(e.message!!.contains("`label`") && e.message!!.contains("`str`"), e.message)

        val badParam = description(extraFunction = ",\n" + """{"name": "greet", "symbol": "kit_greet", "line": 12, "params": [{"name": "who", "type": "str"}], "returns": []}""")
        val p = assertFailsWith<GradleException> { parseAotLibraryDescription(badParam) }
        assertTrue(p.message!!.contains("`greet`") && p.message!!.contains("`str`"), p.message)
    }

    @Test
    fun namesThatCannotBeGeneratedAreRefused() {
        val d = parseAotLibraryDescription(description())
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "not a package", "Kit") }
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "fixture.kit", "class") }
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "fixture.kit", "F64List") }
        val reserved = parseAotLibraryDescription(
            description(extraFunction = ",\n" + """{"name": "load", "symbol": "kit_load", "line": 13, "params": [], "returns": []}"""),
        )
        val e = assertFailsWith<GradleException> { renderAotLibraryBindings(reserved, "fixture.kit", "Kit") }
        assertTrue(e.message!!.contains("`load`"), e.message)
    }

    @Test
    fun theTaskWritesTheFilesIntoThePackageDirectoryAndFailsOnABadDescription() {
        val project = ProjectBuilder.builder().build()
        val json = project.file("kit.json").apply { writeText(description()) }
        val out = project.layout.buildDirectory.dir("generated/aot/kit")
        val task = project.tasks.register("generateKit", GenerateAotLibraryBindingsTask::class.java) {
            descriptionFile.set(json)
            packageName.set("fixture.kit")
            objectName.set("Kit")
            outputDirectory.set(out)
        }.get()
        task.generate()
        val dir = out.get().asFile.resolve("fixture/kit")
        assertEquals(setOf("AotFfm.kt", "Kit.kt", "F64List.kt", "I64List.kt"), dir.list()!!.toSet())

        // a stale file of an earlier object name does not stay behind
        dir.resolve("Old.kt").writeText("x")
        task.generate()
        assertFalse(dir.resolve("Old.kt").exists())

        json.writeText(description(abi = 3))
        assertFailsWith<GradleException> { task.generate() }
    }
}
