    @Test
    fun aWrongAbiVersionIsAClearFailure() {
        // Version 1 is rejected too: no version 1 library is deployed and the compiler writes 2 only.
        for (wrong in listOf(1, 3)) {
            val e = assertFailsWith<GradleException> { parseAotLibraryDescription(description(abi = wrong)) }
            assertTrue(e.message!!.contains("abi_version $wrong"), e.message)
            assertTrue(e.message!!.contains("reads abi_version 2 only"), e.message)
        }
        assertEquals(2, AOT_LIBRARY_ABI_VERSION)
        assertFailsWith<GradleException> { parseAotLibraryDescription(description().replace("\"abi_version\": 2,", "")) }
    }

    @Test
    fun anUnknownTypeFailsNamingTheFunction() {
        val badReturn = description(extraFunction = ",\n" + """{"name": "label", "symbol": "kit_label", "line": 11, "params": [], "returns": ["str"]}""")
        val e = assertFailsWith<GradleException> { parseAotLibraryDescription(badReturn) }
        assertTrue(e.message!!.contains("`label`") && e.message!!.contains("`str`"), e.message)

        val badParam = description(extraFunction = ",\n" + """{"name": "greet", "symbol": "kit_greet", "line": 12, "params": [{"name": "who", "type": "str"}], "returns": []}""")
        val p = assertFailsWith<GradleException> { parseAotLibraryDescription(badParam) }
        assertTrue(p.message!!.contains("`greet`") && p.message!!.contains("`str`"), p.message)
    }

    @Test
    fun namesThatCannotBeGeneratedAreRefused() {
        val d = parseAotLibraryDescription(description())
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "not a package", "Kit") }
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "fixture.kit", "class") }
        assertFailsWith<GradleException> { renderAotLibraryBindings(d, "fixture.kit", "F64List") }
        val reserved = parseAotLibraryDescription(
            description(extraFunction = ",\n" + """{"name": "load", "symbol": "kit_load", "line": 13, "params": [], "returns": []}"""),
        )
        val e = assertFailsWith<GradleException> { renderAotLibraryBindings(reserved, "fixture.kit", "Kit") }
        assertTrue(e.message!!.contains("`load`"), e.message)
    }

    @Test
    fun theTaskWritesTheFilesIntoThePackageDirectoryAndFailsOnABadDescription() {
        val project = ProjectBuilder.builder().build()
        val json = project.file("kit.json").apply { writeText(description()) }
        val out = project.layout.buildDirectory.dir("generated/aot/kit")
        val task = project.tasks.register("generateKit", GenerateAotLibraryBindingsTask::class.java) {
            descriptionFile.set(json)
            packageName.set("fixture.kit")
            objectName.set("Kit")
            outputDirectory.set(out)
        }.get()
        task.generate()
        val dir = out.get().asFile.resolve("fixture/kit")
        assertEquals(setOf("AotFfm.kt", "Kit.kt", "F64List.kt", "I64List.kt"), dir.list()!!.toSet())

        // a stale file of an earlier object name does not stay behind
        dir.resolve("Old.kt").writeText("x")
        task.generate()
        assertFalse(dir.resolve("Old.kt").exists())

        json.writeText(description(abi = 1))
        assertFailsWith<GradleException> { task.generate() }
    }
