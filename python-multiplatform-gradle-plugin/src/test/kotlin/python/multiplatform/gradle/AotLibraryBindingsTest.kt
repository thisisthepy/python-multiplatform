        assertTrue(kit.contains("data class SplitPairResult(val v0: Long, val v1: Double, val v2: Boolean)"), kit)
        assertTrue(kit.contains("data class TwoResult(val v0: Long, val v1: Long)"), kit)
        assertTrue(
            kit.contains(
