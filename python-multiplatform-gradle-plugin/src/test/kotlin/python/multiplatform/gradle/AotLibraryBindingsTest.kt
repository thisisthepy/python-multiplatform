        )
    }

    @Test
    fun aKotlinHardKeywordIsBackticked() {
        val kit = objectText
        assertTrue(kit.contains("    fun keywords(`in`: Long, `object`: Double): Double {"), kit)
        assertTrue(kit.contains("kit_keywords"), kit)
        assertTrue(kit.contains("    fun `when`() {"), "a function named like a keyword")
        assertTrue(kit.contains("f_keywords.invokeExact(`in`, `object`, __out) as Int"), kit)
        assertEquals("`in`", aotKotlinName("in"))
        assertEquals("`val`", aotKotlinName("val"))
        assertEquals("steps", aotKotlinName("steps"))
    }

    @Test
    fun theDescriptorOfEachSymbolIsMadeOfCarrierTypesOnly() {
        val kit = objectText
        // J long (every pointer and int64_t), D double, B byte (uint8_t), I int status; out pointers are J.
        for ((symbol, descriptor) in mapOf(
            "kit_add" to "(JJJ)I",
            "kit_scale" to "(DBJ)I",
            "kit_is_big" to "(DJ)I",
            "kit_fill" to "(JJ)I",
            "kit_make_values" to "(JJ)I",
            "kit_make_ints" to "(J)I",
            "kit_split_pair" to "(JJJJ)I",
            "kit_two" to "(JJ)I",
            "kit_keywords" to "(JDJ)I",
            "kit_when" to "()I",
            "kit_init" to "()I",
            "kit_last_error" to "(JJ)I",
            "kit_f64_list_new" to "(J)J",
            "kit_f64_list_len" to "(J)J",
            "kit_f64_list_data" to "(J)J",
            "kit_f64_list_retain" to "(J)V",
            "kit_i64_list_release" to "(J)V",
        )) {
            assertTrue(kit.contains("rt.downcall(\"$symbol\", \"$descriptor\")"), "$symbol should be bound as $descriptor:\n$kit")
        }
    }

    @Test
    fun noDescriptorUsesAnAddressOrAnObjectCarrier() {
        val all = render().values.joinToString("\n")
        assertFalse(Regex("rt\\.downcall\\(\"[^\"]+\", \"[^\"]*[^JDBIV()][^\"]*\"\\)").containsMatchIn(all))
        assertFalse(all.contains("ADDRESS"), "pointers are JAVA_LONG, never ADDRESS")
        assertTrue(render().getValue("AotFfm.kt").contains("getField(\"JAVA_LONG\")"))
    }

    @Test
    fun aCallIsOneInvokeExactAndAFailureThrowsTheLibrariesException() {
        val kit = objectText
        assertTrue(kit.contains("val __rc = __h.f_add.invokeExact(a, b, __out) as Int"), kit)
        assertTrue(kit.contains("if (__rc != 0) throw __h.rt.lastError(__h.lastError)"), kit)
        // the per-call code never reflects and never uses the inexact invoke
        assertFalse(kit.contains(".invoke("), "generated functions must not use MethodHandle.invoke")
        assertFalse(kit.contains("getMethod"), kit)
        // bool arguments are bytes, lists are their handles, the status is read before the out value
        assertTrue(kit.contains("f_scale.invokeExact(x, (if (flag) 1 else 0).toByte(), __out) as Int"), kit)
        assertTrue(kit.contains("f_fill.invokeExact(v.pointer(), w.pointer()) as Int"), kit)
        assertTrue(
            kit.indexOf("if (__rc != 0) throw", kit.indexOf("fun add(")) < kit.indexOf("return __h.rt.readLong(__out)", kit.indexOf("fun add(")),
        )
        // a returned list becomes an owned handle
        assertTrue(kit.contains("return F64List.owned(__h, __h.rt.readLong(__out))"), kit)
        assertTrue(kit.contains("return I64List.owned(__h, __h.rt.readLong(__out))"), kit)
        // a function with no result has no out pointer
        assertFalse(kit.substringAfter("fun fill(").substringBefore("}").contains("__out"))
    }

    @Test
    fun theObjectLoadsOnceAndTheHelperReadsTheErrorRecord() {
        val kit = objectText
        assertTrue(kit.contains("object Kit {"), kit)
        assertTrue(kit.contains("    @Synchronized\n    fun load(libraryPath: String) {"), kit)
        assertTrue(kit.contains("handles.aotInit.invokeExact() as Int"), kit)
        val helper = render().getValue("AotFfm.kt")
        assertTrue(helper.contains("class TypedPythonAotException(val className: String, message: String) : RuntimeException(message)"))
        assertTrue(helper.contains("fun lastError(lastErrorHandle: MethodHandle): TypedPythonAotException"))
        assertTrue(helper.contains("ThreadLocal.withInitial"), "out pointers live in per-thread scratch memory")
    }

    @Test
    fun theListClassesAreClosableBoundsCheckedAndNameTheLibraryObject() {
        val f64 = render().getValue("F64List.kt")
        assertTrue(f64.contains("class F64List private constructor(private val lib: Kit.Handles, pointer: Long) : AutoCloseable {"), f64)
        assertTrue(f64.contains("operator fun get(index: Int): Double {"), f64)
        assertTrue(f64.contains("operator fun set(index: Int, value: Double) {"), f64)
