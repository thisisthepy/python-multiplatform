"""The error message of `int(s)` in the AOT runtime (SPEC N-17, #462): `repr(str)` of the argument and the decoding of
program arguments, compared with the reference interpreter over EVERY code point and over random strings.

`int(sys.argv[i])` is the user's input at run time, so for every possible argument the executable must print what
CPython prints: for an invalid string `ValueError: invalid literal for int() with base 10: <repr of the string>`, where
the reference's `repr` shows a printable character as it is and escapes the others (`\\xNN`, `\\uNNNN`, `\\UNNNNNNNN`),
which depends on the Unicode version of the interpreter (17.0 in 3.15: `str.isprintable`), keeps the first 200
characters of the repr (a long one is cut, even inside an escape), and shows a byte of an argument that is not valid
UTF-8 as the lone surrogate U+DC00 + byte (`\\udcXX`): the file system encoding's surrogateescape handler, 3.15 runs in
UTF-8 mode. The table of non-printable ranges in `runtime/tp_aot_int.h` is generated by
`python-multiplatform-ksp/tools/gen_aot_nonprintable.py` from the interpreter that runs it.

The harness is one small C program (the only executable this file builds, built once) that includes the runtime and
reads lines on standard input: `R <hex code points>` runs `tpa_int_from_cps` (the runtime's `int()` of a str), `B <hex
bytes>` first decodes the bytes as an argument (`tpa_int__argv_decode`). It answers `V <decimal digits>` or `E
<class>: <message>`. Under the CI sanitizer job it runs with ASan, UBSan and the leak checker, so a leak of the decoded
code points or of a big integer on any path is reported.

The tests that compare with the interpreter are skipped, and only they, when its Unicode version is not the one the
table pins (`PINNED_UNICODE`); the tests of the table's text need no compiler.

Everything here is an agent proposal, not owner-confirmed (the representation and the pinned table: leader, 2026-11-16,
not owner-confirmed, #462).
"""
import importlib.util
import os
import random
import re
import shutil
import subprocess
import sys
import unicodedata
from pathlib import Path
from types import SimpleNamespace

import pytest

from typedpython import aot, cbuild
from typedpython.aot import cc

PINNED_UNICODE = "17.0.0"
HEADER = cc.RUNTIME_DIR / "tp_aot_int.h"
TOOL = Path(__file__).resolve().parents[3] / "tools" / "gen_aot_nonprintable.py"

HARNESS = r'''
#include "tp_aot.h"
#include "tp_aot_int.h"

static int hexdigit(int c)
{
    if (c >= '0' && c <= '9') {
        return c - '0';
    }
    if (c >= 'a' && c <= 'f') {
        return c - 'a' + 10;
    }
    if (c >= 'A' && c <= 'F') {
        return c - 'A' + 10;
    }
    return -1;
}

int main(void)
{
    static char line[1 << 22];
    static uint32_t cps[1 << 20];
    static char bytes[1 << 20];
    while (fgets(line, sizeof line, stdin) != NULL) {
        size_t m = 0, n = 0;
        char *p = line + 1;
        tpa_int v = TPA_INT_ZERO;
        int rc;
        if (line[0] == 'R') {
            for (;;) {
                char *end;
                while (*p == ' ') {
                    p++;
                }
                if (*p == '\0' || *p == '\n' || *p == '\r') {
                    break;
                }
                cps[m++] = (uint32_t)strtoul(p, &end, 16);
                p = end;
            }
            rc = tpa_int_from_cps(cps, m, &v);
        }
        else {
            while (*p == ' ') {
                p++;
            }
            while (hexdigit(p[0]) >= 0 && hexdigit(p[1]) >= 0) {
                bytes[n++] = (char)(hexdigit(p[0]) * 16 + hexdigit(p[1]));
                p += 2;
            }
            m = tpa_int__argv_decode(bytes, n, cps);
            rc = tpa_int_from_cps(cps, m, &v);
        }
        if (rc == 0) {
            char *s;
            size_t len;
            if (tpa_int_to_str(v, &s, &len) == 0) {
                printf("V %s\n", s);
                free(s);
            }
            else {
                printf("E %s: %s\n", tpa_exc_name(tpa_exc.kind), tpa_exc.msg);
            }
            tpa_int_release(v);
        }
        else {
            printf("E %s: %s\n", tpa_exc_name(tpa_exc.kind), tpa_exc.msg);
        }
    }
    fflush(stdout);
    return 0;
}
'''


def need_cc():
    if sys.version_info < (3, 14):
        pytest.skip("the AOT runtime carries the exception messages of CPython 3.14 and later")
    try:
        if cbuild._is_msvc():
            cbuild.msvc_env()
        elif shutil.which(cbuild.compiler()[0]) is None:
            pytest.skip("no C compiler")
    except cbuild.CBuildError as e:
        pytest.skip(str(e))


def need_pinned_unicode():
    """The runtime's tables hold the Unicode data of the reference interpreter they were generated with. A
    reference with other data is not a reason to skip (a skip passes silently): it means the tables are stale,
    so the test fails and says what to do (leader, 2026-11-16)."""
    assert unicodedata.unidata_version == PINNED_UNICODE, (
        f"this interpreter's Unicode is {unicodedata.unidata_version}, the runtime's tables hold {PINNED_UNICODE}: "
        "regenerate them (python-multiplatform-ksp/tools/gen_aot_nonprintable.py --write, and the decimal digit "
        "table of tp_aot_int.h) and update PINNED_UNICODE")


def exe_env():
    env = dict(os.environ)
    if env.get("TP_SANITIZE") == "1":
        env.pop("LD_PRELOAD", None)
        env["ASAN_OPTIONS"] = f"detect_leaks={'1' if sys.platform.startswith('linux') else '0'}:abort_on_error=0:halt_on_error=1"
        env["UBSAN_OPTIONS"] = "halt_on_error=1:print_stacktrace=1"
    return env


def tool():
    spec = importlib.util.spec_from_file_location("gen_aot_nonprintable", str(TOOL))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def harness(tmp_path_factory):
    need_cc()
    tmp = tmp_path_factory.mktemp("repr_harness")
    return cc.compile_executable(HARNESS, tmp / "repr_harness")


def run_harness(exe, lines: list[str]) -> list[str]:
    run = subprocess.run([str(exe)], input=("\n".join(lines) + "\n").encode("ascii"), capture_output=True,
                         env=exe_env(), timeout=600)
    assert run.returncode == 0, run.stderr.decode("utf-8", "replace")[-2000:]
    out = run.stdout.decode("utf-8").replace("\r\n", "\n").split("\n")
    assert out.pop() == "", "the harness ends every answer with a newline"
    assert len(out) == len(lines), (len(out), len(lines))
    return out


def cp_line(s: str) -> str:
    return "R " + " ".join(f"{ord(c):x}" for c in s)


def byte_line(b: bytes) -> str:
    return "B " + b.hex()


def expected_for_string(s: str) -> str:
    """What the reference does with `int(s)`, in the harness's format (`str` of a result over 4300 digits raises)."""
    try:
        return "V " + str(int(s))
    except ValueError as e:
        return f"E ValueError: {e}"


def compare(exe, strings: list[str]) -> None:
    got = run_harness(exe, [cp_line(s) for s in strings])
    bad = [(s, g, expected_for_string(s)) for s, g in zip(strings, got) if g != expected_for_string(s)]
    assert not bad, f"{len(bad)} of {len(strings)} differ, first: {bad[0]!r}"


# --- text tests (no compiler) ------------------------------------------------------------------------------

def test_the_table_in_the_header_is_the_one_the_script_generates():
    need_pinned_unicode()
    module = tool()
    body = HEADER.read_text(encoding="utf-8")
    a, b = body.index(module.BEGIN), body.index(module.END) + len(module.END)
    assert body[a:b] == module.block(), "regenerate it: python-multiplatform-ksp/tools/gen_aot_nonprintable.py --write"
    assert f'#define TPA_INT_UNICODE_VERSION "{PINNED_UNICODE}"' in body[a:b]


def test_the_script_says_how_to_regenerate_the_table_and_which_unicode_version_it_holds():
    text = TOOL.read_text(encoding="utf-8")
    assert "--write" in text and "Unicode 17.0.0" in text and "Regenerate" in text
    assert chr(0x2014) not in text
    body = HEADER.read_text(encoding="utf-8")
    assert "tpa_int__nonprint" in body and "gen_aot_nonprintable.py" in body and chr(0x2014) not in body


def test_the_table_is_sorted_disjoint_maximal_and_has_no_ascii():
    module = tool()
    text = HEADER.read_text(encoding="utf-8")
    flat = [int(x, 16) for x in re.findall(r"0x([0-9A-F]+)", text[text.index(module.BEGIN):text.index(module.END)])]
    ranges = list(zip(flat[0::2], flat[1::2]))
    assert len(flat) % 2 == 0 and ranges and ranges[0][0] >= 0x80 and ranges[-1][1] == 0x10FFFF
    assert f"#define TPA_INT__NONPRINT_N {len(ranges)}" in text
    for (a, b), (c, d) in zip(ranges, ranges[1:]):
        assert a <= b < c <= d and b + 1 < c, "maximal ranges: sorted, disjoint, not adjacent"


# --- against the reference interpreter ----------------------------------------------------------------------

def test_every_code_point_as_a_one_character_string(harness):
    need_pinned_unicode()
    chunk = 1 << 17
    for start in range(0, 0x110000, chunk):
        compare(harness, [chr(cp) for cp in range(start, min(start + chunk, 0x110000))])


SPECIAL = ["'", '"', "\\", "\n", "\t", "\r", "\x7f", "\x00", "\x85", "\xa0", "\xe9", "​", "̀", " ",
           "\U0001f600", "\U0010ffff", "", "\ud800", "\udcff", "٣", "­"]


def test_a_character_at_every_position_around_the_truncation_at_200_characters(harness):
    need_pinned_unicode()
    strings = []
    for k in range(190, 206):
        for ch in SPECIAL:
            strings.append("x" * k + ch)
            strings.append("'" + "x" * (k - 1) + ch + "z")
            strings.append(ch * k)
    compare(harness, strings)


def test_random_strings_of_every_kind(harness):
    need_pinned_unicode()
    rnd = random.Random(20261116)
    pool = [*SPECIAL, *"0123456789", *" +-_", "a", "e", "x", "١", "۱", " ", "　", "²", "−",
            "\U0001d7ce", "\U0001e950"]
    strings = []
    for _ in range(40000):
        n = rnd.choice([0, 1, 2, 3, 4, 6, 9, 17, 60, 150, 198, 199, 200, 201, 260, 400])
        parts = []
        for _ in range(n):
            k = rnd.random()
            if k < 0.45:
                parts.append(rnd.choice(pool))
            elif k < 0.6:
                parts.append(chr(rnd.randrange(0x20, 0x7F)))
            elif k < 0.85:
                parts.append(chr(rnd.randrange(0x80, 0x3000)))
            else:
                parts.append(chr(rnd.randrange(0, 0x110000)))
        strings.append("".join(parts))
    # valid ints in unusual spellings, and the digit limit
    strings += [" 12 ", "+1_000", "-0", " 7 ", "٣٢", "1" * 4300, "1" * 4301, "-" + "9" * 4300,
                " " + "7" * 4301 + " ", "1_" * 100 + "1", "١" * 4301, "1" * 4301 + "x", "x" + "1" * 5000]
    compare(harness, strings)


def test_program_arguments_are_decoded_as_the_reference_decodes_them(harness):
    """The undecodable bytes of an argument become lone surrogates (surrogateescape): the harness decodes bytes as the
    runtime does for `sys.argv[i]`, and `bytes.decode('utf-8', 'surrogateescape')` is what the interpreter's argument
    decoding does (also checked against real arguments by the executables of test_aot_build.py)."""
    need_pinned_unicode()
    rnd = random.Random(7)
    alphabet = [b"\xc3", b"\xa9", b"\xe2", b"\x82", b"\xac", b"\xf0", b"\x9f", b"\x98", b"\x80", b"\xed", b"\xa0", b"\xf4",
                b"\x90", b"\xc0", b"\xc1", b"\xf5", b"\xff", b"A", b"1", b" ", b"\xe0", b"\xbf", b"\x8f", b"_", b"'", b"\\"]
    inputs = [b"", b"\xff", b"1\xff", b"\xc3\xa9", b"\xe2\x82", b"\xf0\x9f\x98\x80", b"\xed\xa0\x80", b"\xc0\x80",
              b"\xf4\x90\x80\x80", b"\xe0\x80\x80", b"\x80\x80", b"\xf0\x9f\x98", b"7\xe2\x82", b"1\xc3\x28"]
    for _ in range(30000):
        inputs.append(b"".join(rnd.choice(alphabet) for _ in range(rnd.randrange(1, 12))))
    got = run_harness(harness, [byte_line(b) for b in inputs])
    bad = []
    for b, g in zip(inputs, got):
        want = expected_for_string(b.decode("utf-8", "surrogateescape"))
        if g != want:
            bad.append((b, g, want))
    assert not bad, f"{len(bad)} of {len(inputs)} differ, first: {bad[0]!r}"


def test_the_pinned_messages_of_the_reference_for_arguments_that_are_not_ints(harness):
    """Literal, so that a change of the reference interpreter shows here."""
    need_pinned_unicode()
    got = run_harness(harness, [byte_line(b"\xff"), byte_line(b"7\xe2\x82"), byte_line("é".encode()), byte_line(b"1_"),
                                byte_line("😀".encode()), byte_line(b"a'b"), byte_line(b"")])
    p = "E ValueError: invalid literal for int() with base 10: "
    assert got == [p + "'\\udcff'", p + "'7\\udce2\\udc82'", p + "'é'", p + "'1_'", p + "'😀'", p + '"a\'b"', p + "''"]
