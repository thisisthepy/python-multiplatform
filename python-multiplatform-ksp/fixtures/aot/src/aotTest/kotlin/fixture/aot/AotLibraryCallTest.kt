    private class Run(val e0: Double, val e1: Double, val arrays: Map<String, DoubleArray>)

    /** The full simulation of benchmarks/typedpython/py/nbody.py's `main`, through the generated wrappers. */
    private fun simulate(steps: Long): Run {
        val lists = linkedMapOf(
            "x" to Nbody.make_x(), "y" to Nbody.make_y(), "z" to Nbody.make_z(),
            "vx" to Nbody.make_vx(), "vy" to Nbody.make_vy(), "vz" to Nbody.make_vz(), "mass" to Nbody.make_mass(),
        )
        try {
            val x = lists.getValue("x")
            val y = lists.getValue("y")
            val z = lists.getValue("z")
            val vx = lists.getValue("vx")
            val vy = lists.getValue("vy")
            val vz = lists.getValue("vz")
            val mass = lists.getValue("mass")
            Nbody.offset_momentum(vx, vy, vz, mass)
            val e0 = Nbody.energy(x, y, z, vx, vy, vz, mass)
            Nbody.advance(0.01, steps, x, y, z, vx, vy, vz, mass)
            val e1 = Nbody.energy(x, y, z, vx, vy, vz, mass)
            return Run(e0, e1, lists.mapValues { it.value.toDoubleArray() })
        } finally {
            lists.values.forEach { it.close() }
        }
    }

    private fun assertSameRun(expected: Run, actual: Run, what: String) {
        assertBits(expected.e0, actual.e0, "$what: energy before")
        assertBits(expected.e1, actual.e1, "$what: energy after")
        for ((name, values) in expected.arrays) {
            for (i in values.indices) assertBits(values[i], actual.arrays.getValue(name)[i], "$what: $name[$i]")
        }
    }

    private fun assertBits(expected: Double, actual: Double, what: String) {
        assertEquals(
            expected.toRawBits(), actual.toRawBits(),
            "$what: expected ${java.lang.Double.toHexString(expected)} but was ${java.lang.Double.toHexString(actual)}",
        )
    }

    /** The shared library's path: the directory of the `<prefix>.json` `aot-lib` wrote and the file name it names. */
    private fun libraryPath(prefix: String): String {
        val description = File(assertNotNull(System.getProperty("aot.$prefix.description"), "aot.$prefix.description is not set"))
        assertTrue(description.isFile, "$description does not exist: the library build did not run")
        val name = Regex("\"library\"\\s*:\\s*\"([^\"]+)\"").find(description.readText())?.groupValues?.get(1)
        assertNotNull(name, "no \"library\" in $description")
        val library = File(description.parentFile, name)
        assertTrue(library.isFile, "$library does not exist")
        return library.absolutePath
    }

