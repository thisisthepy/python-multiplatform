/**
 * TypedPython AOT libraries (SPEC N-17, #458) called from Kotlin on the desktop JVM, with no CPython.
 *
 * Two libraries are built by `python -m typedpython aot-lib` (see build.gradle.kts): `nbody` from
 * benchmarks/typedpython/py/nbody.py, and `errors` from src/desktopTest/aot/errors.py. The Kotlin that calls them
 * (`fixture.aot.nbody.Nbody`, `fixture.aot.errors.Errors` and their list classes) is generated by
 * `GenerateAotLibraryBindingsTask` from the `<prefix>.json` each build wrote. Nothing in this module depends on
 * python-multiplatform.
 *
 * Provenance. The library output is owner decision D5 (2026-11-16); desktop JVM first and the self-contained
 * generated Kotlin are leader decisions of 2026-11-16, not owner-confirmed; this test is an agent proposal,
 * not owner-confirmed.
 *
 * Every expected value below comes from the reference interpreter, plain CPython 3.15.0rc1 (free-threaded) running
 * the same source, not from the compiled library:
 *
 *     python-multiplatform-ksp/.venv/bin/python -c "
 *     import sys; sys.path.insert(0, 'benchmarks/typedpython/py'); import nbody as n
 *     x,y,z,vx,vy,vz,m = (f() for f in (n.make_x, n.make_y, n.make_z, n.make_vx, n.make_vy, n.make_vz, n.make_mass))
 *     n.offset_momentum(vx, vy, vz, m); print(n.energy(x,y,z,vx,vy,vz,m).hex())
 *     n.advance(0.01, STEPS, x,y,z,vx,vy,vz,m); print(n.energy(x,y,z,vx,vy,vz,m).hex(), [l[i].hex() for l in (...) for i in (0,1,4)])"
 *
 * for STEPS in 500, 1000 and 2000, and `import errors` from src/desktopTest/aot for the exception classes and
 * messages (`errors.rem(1, 0)`, `errors.at([1.0], 5)`, ...). Floating-point values are hex-float literals, so a
 * comparison is bit for bit.
 */
class AotLibraryCallTest {

    @BeforeTest
    fun load() {
        val skip = System.getProperty("aot.skip")
        assumeTrue("AOT library tests not run: $skip", skip == null)
        Nbody.load(libraryPath("nbody"))
        Errors.load(libraryPath("errors"))
    }

    // --- nbody: the kernels of benchmarks/typedpython/py/nbody.py, bit for bit -----------------------------

    @Test
    fun nbodyEnergiesAndPositionsEqualCPythonBitForBit() {
        val run = simulate(1000)
        assertBits(E0, run.e0, "energy before")
        assertBits(REF_1000.getValue("e1")[0], run.e1, "energy after 1000 steps")
        for (name in listOf("x", "y", "z", "vx", "vy", "vz")) {
            val expected = REF_1000.getValue(name)
            for ((k, i) in SAMPLE.withIndex()) assertBits(expected[k], run.arrays.getValue(name)[i], "$name[$i]")
        }
    }

    @Test
    fun otherStepCountsAlsoEqualCPython() {
        for ((steps, ref) in mapOf(500L to REF_500, 2000L to REF_2000)) {
            val run = simulate(steps)
            assertBits(ref.getValue("e1")[0], run.e1, "energy after $steps steps")
            for (name in listOf("x", "vz")) {
                for ((k, i) in SAMPLE.withIndex()) assertBits(ref.getValue(name)[k], run.arrays.getValue(name)[i], "$steps $name[$i]")
            }
        }
    }

    // --- errors: the class name and message CPython gives --------------------------------------------------

    @Test
    fun aPythonExceptionArrivesAsTypedPythonAotExceptionWithCPythonsClassAndMessage() {
        val zero = assertFailsWith<TypedPythonAotException> { Errors.rem(1, 0) }
        assertEquals("ZeroDivisionError", zero.className)
        assertEquals("division by zero", zero.message)
        assertEquals("ZeroDivisionError: division by zero", zero.toString())
        assertEquals(1L, Errors.rem(7, 3), "a call after a failure succeeds")

        ErrF64List.of(doubleArrayOf(1.0)).use { v ->
            val outOfRange = assertFailsWith<TypedPythonAotException> { Errors.at(v, 5) }
            assertEquals("IndexError", outOfRange.className)
            assertEquals("list index out of range", outOfRange.message)
            assertEquals(1.0, Errors.at(v, 0), "a call after a failure succeeds")
        }
        ErrI64List(0).use { empty ->
            val e = assertFailsWith<TypedPythonAotException> { Errors.largest(empty) }
            assertEquals("IndexError", e.className)
            assertEquals("list index out of range", e.message)
        }
    }

    // --- lists --------------------------------------------------------------------------------------------

    @Test
    fun aListIsCreatedReadWrittenAndConvertedBack() {
        ErrF64List.of(doubleArrayOf(1.5, 2.5, 3.5)).use { v ->
            assertEquals(3, v.size)
            assertEquals(2.5, v[1])
            v[1] = 9.25
            assertEquals(9.25, v[1])
            assertContentEquals(doubleArrayOf(1.5, 9.25, 3.5), v.toDoubleArray())
            Errors.set_first(v, -4.0)
            assertEquals(-4.0, v[0], "a write by the library is seen from Kotlin")
        }
        ErrF64List(4).use { zeros -> assertContentEquals(DoubleArray(4), zeros.toDoubleArray()) }
        ErrI64List.of(longArrayOf(3, 9, -2)).use { w -> assertContentEquals(longArrayOf(3, 9, -2), w.toLongArray()) }
    }

    @Test
    fun indexesAreCheckedOnTheKotlinSide() {
        ErrF64List(2).use { v ->
            assertFailsWith<IndexOutOfBoundsException> { v[2] }
            assertFailsWith<IndexOutOfBoundsException> { v[-1] }
            assertFailsWith<IndexOutOfBoundsException> { v[2] = 1.0 }
            assertFailsWith<IndexOutOfBoundsException> { v[-1] = 1.0 }
        }
    }

    @Test
    fun useAfterCloseThrowsAndCloseIsIdempotent() {
        val v = ErrF64List(2)
        assertFalse(v.isClosed)
        v.close()
        assertTrue(v.isClosed)
        v.close()
        assertFailsWith<IllegalStateException> { v[0] }
        assertFailsWith<IllegalStateException> { v[0] = 1.0 }
        assertFailsWith<IllegalStateException> { v.toDoubleArray() }
        assertFailsWith<IllegalStateException> { Errors.at(v, 0) }
    }

    @Test
    fun aFunctionThatReturnsItsArgumentGivesAHandleToTheSameListAndClosingBothIsBalanced() {
        val a = ErrF64List.of(doubleArrayOf(1.0, 2.0))
        val b = Errors.same_list(a)
        assertEquals(2, b.size)
        b[0] = 9.0
        assertEquals(9.0, a[0], "a write through one is seen through the other")
        a[1] = 7.0
        assertEquals(7.0, b[1])
        a.close()
        assertEquals(9.0, b[0], "the list outlives the first owner")
        b.close()
        assertTrue(a.isClosed && b.isClosed)
        // The count is internal to the library; if the two closes were not balanced the allocator would fail
        // here or in the thousands of lists the other tests make. Behaviour only:
        repeat(1000) {
            val x = ErrF64List(8)
            val y = Errors.same_list(x)
            x.close()
            y.close()
        }
    }

    @Test
    fun theSameKotlinListForTwoParametersIsOneListInside() {
        // alias_effect(a, b): a[0] = b[0] + 1.0; b[0] = a[0] * 2.0. CPython 3.15, same source (see the class comment):
        // alias_effect(l, l) with l == [5.0] leaves [12.0]; with two lists a == [5.0], b == [5.0] it leaves [6.0] and [12.0].
        ErrF64List.of(doubleArrayOf(5.0)).use { l ->
            Errors.alias_effect(l, l)
            assertEquals(12.0, l[0], "one list passed twice is one list inside")
        }
        ErrF64List.of(doubleArrayOf(5.0)).use { a ->
            ErrF64List.of(doubleArrayOf(5.0)).use { b ->
                Errors.alias_effect(a, b)
                assertEquals(6.0, a[0])
                assertEquals(12.0, b[0])
            }
        }
    }

    // --- scalars, bool, tuple ---------------------------------------------------------------------------

    @Test
    fun boolAndTupleRoundTrips() {
        assertFalse(Errors.flip(true))
        assertTrue(Errors.flip(false))
        assertEquals(TripleResult(2L, 3.5, true), Errors.triple(7))
        assertEquals(TripleResult(-2L, -2.5, false), Errors.triple(-5))
        assertEquals(2.0, Errors.keywords(`val` = 3.0, `object` = 1.0), "parameters named like Kotlin keywords keep their names")
    }

    @Test
    fun anIntListIsPassedAndAnIntListIsReturned() {
        ErrI64List.of(longArrayOf(3, 9, -2)).use { w -> assertEquals(9L, Errors.largest(w)) }
        Errors.count_up(5).use { r ->
            assertEquals(5, r.size)
            assertContentEquals(longArrayOf(0, 1, 2, 3, 4), r.toLongArray())
            r[0] = 100
            assertEquals(100L, Errors.largest(r))
        }
    }

    // --- threads -------------------------------------------------------------------------------------------

    @Test
    fun twoThreadsRunTheirOwnSimulationsConcurrentlyAndGetTheSingleThreadedResults() {
        val single500 = simulate(500)
        val single2000 = simulate(2000)
        repeat(5) {
            val pool = Executors.newFixedThreadPool(2)
            try {
                val start = CountDownLatch(1)
                val a: Future<Run> = pool.submit<Run> { start.await(); simulate(500) }
                val b: Future<Run> = pool.submit<Run> { start.await(); simulate(2000) }
                start.countDown()
                assertSameRun(single500, a.get(120, TimeUnit.SECONDS), "thread A")
                assertSameRun(single2000, b.get(120, TimeUnit.SECONDS), "thread B")
            } finally {
                pool.shutdownNow()
            }
        }
        assertBits(REF_500.getValue("e1")[0], single500.e1, "single-threaded 500 steps equals CPython")
    }

    @Test
    fun anExceptionOnOneThreadDoesNotDisturbTheOther() {
        val single = simulate(2000)
        repeat(3) {
            val pool = Executors.newFixedThreadPool(2)
            try {
                val start = CountDownLatch(1)
                val failing: Future<Int> = pool.submit<Int> {
                    start.await()
                    var failures = 0
                    repeat(2000) {
                        val e = assertFailsWith<TypedPythonAotException> { Errors.rem(1, 0) }
                        assertEquals("ZeroDivisionError", e.className)
                        assertEquals("division by zero", e.message)
                        assertEquals(2L, Errors.rem(8, 3))
                        failures++
                    }
                    failures
                }
                val simulating: Future<Run> = pool.submit<Run> { start.await(); simulate(2000) }
                start.countDown()
                assertEquals(2000, failing.get(120, TimeUnit.SECONDS))
                assertSameRun(single, simulating.get(120, TimeUnit.SECONDS), "the simulating thread")
            } finally {
                pool.shutdownNow()
            }
        }
    }

    // --- no CPython ----------------------------------------------------------------------------------------

    @Test
    fun noClassOfTheCPythonEmbeddingLibraryIsOnTheClasspath() {
        for (name in listOf("python.multiplatform.ffi.PyObject", "python.multiplatform.ffi.Python3", "python.native.ffi.Panama")) {
            assertFailsWith<ClassNotFoundException>("$name must not be loadable") { Class.forName(name) }
            assertFalse(
                javaClass.classLoader.getResources(name.replace('.', '/') + ".class").hasMoreElements(),
                "$name is on the classpath",
            )
        }
    }

    /**
     * The process, not only the classpath: no libpython image is mapped into this JVM. Linux reads
     * /proc/self/maps; macOS asks `vmmap`, then `lsof`, for this process's mapped files (the dyld image
     * list cannot be read with java.base alone). Where neither answers on Linux or macOS the test FAILS
     * rather than passing on the classpath check alone; on any other OS it is skipped, and that skip is
     * the stated limit of this check there.
     */
    @Test
    fun noLibpythonImageIsLoadedInTheProcessLinuxProcMapsMacosVmmapOrLsof() {
        val os = System.getProperty("os.name").lowercase()
        assumeTrue("the loaded images of the process cannot be listed on $os", "linux" in os || "mac" in os)
        // Both libraries are loaded by @BeforeTest, so a libpython they pulled in would show here.
        val images = loadedImages()
            ?: fail("the loaded images of this process could not be listed (proc maps, vmmap and lsof all failed)")
        assertTrue(images.contains("nbody"), "the listing does not show the library loaded by this test, so it proves nothing")
        assertFalse(images.contains("libpython", ignoreCase = true), "a libpython is loaded in the test JVM")
        assertFalse(images.contains("Python.framework"), "a Python framework is loaded in the test JVM")
    }

    /** The mapped files of this process: /proc/self/maps on Linux; on macOS `vmmap -w <pid>`, else `lsof -p <pid>`; null if none worked. */
    private fun loadedImages(): String? {
        val maps = File("/proc/self/maps")
        if (maps.isFile) return maps.readText()
        val pid = ProcessHandle.current().pid().toString()
        return toolOutput("/usr/bin/vmmap", "-w", pid) ?: toolOutput("/usr/sbin/lsof", "-p", pid)
    }

    /** Standard output of a tool that exited 0 within a minute, or null. */
    private fun toolOutput(vararg command: String): String? {
        if (!File(command[0]).canExecute()) return null
        val pool = Executors.newSingleThreadExecutor()
        return try {
            val process = ProcessBuilder(*command).redirectErrorStream(true).start()
            val text = pool.submit<String> { process.inputStream.bufferedReader().readText() }.get(60, TimeUnit.SECONDS)
            if (process.waitFor(10, TimeUnit.SECONDS) && process.exitValue() == 0) text else null
        } catch (e: Exception) {
            null
        } finally {
            pool.shutdownNow()
        }
    }

    // --- helpers -------------------------------------------------------------------------------------------

    private class Run(val e0: Double, val e1: Double, val arrays: Map<String, DoubleArray>)

    /** The full simulation of benchmarks/typedpython/py/nbody.py's `main`, through the generated wrappers. */
    private fun simulate(steps: Long): Run {
        val lists = linkedMapOf(
            "x" to Nbody.make_x(), "y" to Nbody.make_y(), "z" to Nbody.make_z(),
            "vx" to Nbody.make_vx(), "vy" to Nbody.make_vy(), "vz" to Nbody.make_vz(), "mass" to Nbody.make_mass(),
        )
        try {
            val x = lists.getValue("x")
            val y = lists.getValue("y")
            val z = lists.getValue("z")
            val vx = lists.getValue("vx")
            val vy = lists.getValue("vy")
            val vz = lists.getValue("vz")
            val mass = lists.getValue("mass")
            Nbody.offset_momentum(vx, vy, vz, mass)
            val e0 = Nbody.energy(x, y, z, vx, vy, vz, mass)
            Nbody.advance(0.01, steps, x, y, z, vx, vy, vz, mass)
            val e1 = Nbody.energy(x, y, z, vx, vy, vz, mass)
            return Run(e0, e1, lists.mapValues { it.value.toDoubleArray() })
        } finally {
            lists.values.forEach { it.close() }
        }
    }

    private fun assertSameRun(expected: Run, actual: Run, what: String) {
        assertBits(expected.e0, actual.e0, "$what: energy before")
        assertBits(expected.e1, actual.e1, "$what: energy after")
        for ((name, values) in expected.arrays) {
            for (i in values.indices) assertBits(values[i], actual.arrays.getValue(name)[i], "$what: $name[$i]")
        }
    }

    private fun assertBits(expected: Double, actual: Double, what: String) {
        assertEquals(
            expected.toRawBits(), actual.toRawBits(),
            "$what: expected ${java.lang.Double.toHexString(expected)} but was ${java.lang.Double.toHexString(actual)}",
        )
    }

    /** The shared library's path: the directory of the `<prefix>.json` `aot-lib` wrote and the file name it names. */
    private fun libraryPath(prefix: String): String {
        val description = File(assertNotNull(System.getProperty("aot.$prefix.description"), "aot.$prefix.description is not set"))
        assertTrue(description.isFile, "$description does not exist: the library build did not run")
        val name = Regex("\"library\"\\s*:\\s*\"([^\"]+)\"").find(description.readText())?.groupValues?.get(1)
        assertNotNull(name, "no \"library\" in $description")
        val library = File(description.parentFile, name)
        assertTrue(library.isFile, "$library does not exist")
        return library.absolutePath
    }

    private companion object {
