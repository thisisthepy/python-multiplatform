        fun ds(vararg hex: String): DoubleArray = DoubleArray(hex.size) { d(hex[it]) }

        /** The elements of the five-element lists the reference values were taken at. */
        val SAMPLE = intArrayOf(0, 1, 4)

        val E0 = d("-0x1.5a441459acc23p-3")

        val REF_1000: Map<String, DoubleArray> = mapOf(
            "e1" to ds("-0x1.5a4a9a3521fa9p-3"),
