        ErrF64List.of(doubleArrayOf(5.0)).use { a ->
            ErrF64List.of(doubleArrayOf(5.0)).use { b ->
                Errors.alias_effect(a, b)
                assertEquals(6.0, a[0])
                assertEquals(12.0, b[0])
            }
        }
    }

