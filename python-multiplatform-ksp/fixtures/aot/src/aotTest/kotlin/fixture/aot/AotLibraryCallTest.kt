            "y" to ds("0x1.8a803df850b85p-9", "-0x1.40510b95b797dp+2", "-0x1.24196339ab006p+4"),
            "z" to ds("-0x1.17a8c188b18f5p-12", "-0x1.6dae78a876d25p-7", "-0x1.61f3b45f03b17p-3"),
